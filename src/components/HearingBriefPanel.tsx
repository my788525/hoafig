"use client";

import React, { useState } from "react";

interface HearingBriefPanelProps {
  briefTitle: string;
  jurisdictionName: string;
  statuteCitation: string;
  officialGovUrl: string;
  summaryRows: { label: string; value: string; highlight?: "ok" | "warn" | "danger" }[];
  letterText: string;
  violationSummaryText?: string;
}

export default function HearingBriefPanel({
  briefTitle,
  jurisdictionName,
  statuteCitation,
  officialGovUrl,
  summaryRows,
  letterText,
  violationSummaryText,
}: HearingBriefPanelProps) {
  const [copied, setCopied] = useState(false);
  const [copiedSummary, setCopiedSummary] = useState(false);

  const computedSummaryText =
    violationSummaryText ||
    [
      `HOA STATUTORY VIOLATION SUMMARY — ${briefTitle}`,
      `Jurisdiction: ${jurisdictionName} (${statuteCitation})`,
      `--------------------------------------------------`,
      ...summaryRows.map((r) => `${r.label}: ${r.value}`),
      `--------------------------------------------------`,
      `Generated by HOAFig.com (100% Client-Side Audit)`,
    ].join("\n");

  const handleCopy = async () => {
    try {
      await navigator.clipboard.writeText(letterText);
      setCopied(true);
      setTimeout(() => setCopied(false), 2500);
    } catch {}
  };

  const handleCopySummary = async () => {
    try {
      await navigator.clipboard.writeText(computedSummaryText);
      setCopiedSummary(true);
      setTimeout(() => setCopiedSummary(false), 2500);
    } catch {}
  };

  return (
    <div className="space-y-6 mt-8">
      {/* Printable 《HOA Statutory Compliance & Hearing Brief》 */}
      <div className="brief-card print-brief p-6 sm:p-8 bg-white">
        <div className="flex flex-wrap items-start justify-between gap-4 border-b border-slate-200 pb-4">
          <div>
            <div className="text-[11px] font-mono uppercase tracking-widest text-[#0f2747] font-bold">
              《HOA STATUTORY COMPLIANCE &amp; HEARING BRIEF》
            </div>
            <h3 className="text-xl font-extrabold text-[#0f2747] mt-1">{briefTitle}</h3>
            <p className="text-xs text-slate-600 mt-0.5">
              Jurisdiction: <strong>{jurisdictionName}</strong> · Authority:{" "}
              <a
                href={officialGovUrl}
                target="_blank"
                rel="noopener noreferrer"
                className="text-[#0f2747] underline font-semibold"
              >
                {statuteCitation}
              </a>
            </p>
          </div>

          <div className="no-print flex flex-wrap items-center gap-2">
            <button
              type="button"
              onClick={handleCopySummary}
              className="px-3.5 py-2 rounded-lg bg-[#059669] hover:bg-emerald-700 text-white text-xs font-bold transition cursor-pointer"
            >
              {copiedSummary ? "Violation Summary Copied ✓" : "Copy Free Violation Summary"}
            </button>
            <button
              type="button"
              onClick={() => window.print()}
              className="px-4 py-2 rounded-lg bg-[#0f2747] hover:bg-[#1a3b68] text-white text-xs font-bold transition cursor-pointer"
            >
              Print Hearing Brief (PDF)
            </button>
          </div>
        </div>

        <div className="mt-4 divide-y divide-slate-100">
          {summaryRows.map((row, idx) => (
            <div key={idx} className="py-2.5 flex flex-wrap items-center justify-between gap-2 text-sm">
              <span className="text-slate-600 font-medium">{row.label}</span>
              <span
                className={`font-bold tabular-nums ${
                  row.highlight === "danger"
                    ? "text-rose-700"
                    : row.highlight === "warn"
                    ? "text-amber-700"
                    : row.highlight === "ok"
                    ? "text-[#059669]"
                    : "text-[#0f2747]"
                }`}
              >
                {row.value}
              </span>
            </div>
          ))}
        </div>

        <div className="mt-4 pt-3 border-t border-slate-200 text-[11px] text-slate-500 flex flex-wrap justify-between gap-2">
          <span>Generated by HOAFig.com · 100% Client-Side Statutory Audit</span>
          <span>Prepared for Board / Fining Committee Submission</span>
        </div>
      </div>

      {/* Copyable Formal Hearing & Records Request Letter */}
      <div className="brief-card p-6 sm:p-8 bg-slate-50/70 no-print">
        <div className="flex flex-wrap items-center justify-between gap-3 mb-4">
          <div>
            <div className="text-[11px] font-mono uppercase tracking-wider text-[#059669] font-bold">
              CERTIFIED MAIL &amp; EMAIL READY
            </div>
            <h4 className="text-lg font-extrabold text-[#0f2747]">
              Formal Board Hearing &amp; Statutory Records Request Letter
            </h4>
          </div>
          <button
            type="button"
            onClick={handleCopy}
            className="px-4 py-2 rounded-lg bg-[#059669] hover:bg-emerald-700 text-white text-xs font-bold transition cursor-pointer"
          >
            {copied ? "Copied to Clipboard ✓" : "Copy Formal Letter"}
          </button>
        </div>

        <pre className="whitespace-pre-wrap font-mono text-xs text-slate-800 bg-white border border-slate-200 rounded-xl p-4 sm:p-5 leading-relaxed overflow-x-auto">
          {letterText}
        </pre>
      </div>
    </div>
  );
}
